import re

def clean_df_colors(text):
    # Use regex to find all [STATE_COLOR:...] tags to ignore any accidental stray text
    pattern = r"\[STATE_COLOR:[^\]]+\]"
    matches = re.findall(pattern, text)
    
    # Set() automatically removes duplicates; sorted() alphabetizes
    unique_sorted_colors = sorted(list(set(matches)))
    
    return "\n".join(unique_sorted_colors)

