import re

def find_missing_colors(list_a_text, list_b_text):
    # Regex to capture just the color name at the end of the tag
    pattern = r"\[STATE_COLOR:ALL_SOLID:([^\]]+)\]"
    
    # Extract unique color names into sets
    set_a = set(re.findall(pattern, list_a_text))
    set_b = set(re.findall(pattern, list_b_text))
    
    # Identify colors in B that are NOT in A
    missing_from_a = sorted(list(set_b - set_a))
    
    print(f"--- Analysis Complete ---")
    print(f"Colors in List A (Stripped): {len(set_a)}")
    print(f"Colors in List B (Master): {len(set_b)}")
    print(f"Unique colors in B not found in A: {len(missing_from_a)}")
    print("\nMissing Color Tags:")
    
    for color in missing_from_a:
        print(f"[STATE_COLOR:ALL_SOLID:{color}]")

