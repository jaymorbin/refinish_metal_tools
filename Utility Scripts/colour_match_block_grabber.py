import re

def filter_inorganic_blocks(color_list_text, raw_file_text):
    # 1. Extract the unique color names from your provided [STATE_COLOR...] tags
    color_pattern = r"\[STATE_COLOR:ALL_SOLID:([^\]]+)\]"
    target_colors = set(re.findall(color_pattern, color_list_text))
    
    # 2. Split the raw file into individual INORGANIC blocks
    # We split by the [INORGANIC: tag, but keep the tag using a lookahead
    blocks = re.split(r'(?=\[INORGANIC:)', raw_file_text)
    
    matched_blocks = []
    
    # 3. Iterate through blocks and check for a color match
    for block in blocks:
        if not block.strip():
            continue
            
        # Extract the specific color name defined in this block
        match = re.search(color_pattern, block)
        if match:
            block_color = match.group(1)
            if block_color in target_colors:
                matched_blocks.append(block.strip())
    
    # 4. Output the results
    print(f"--- Search Complete ---")
    print(f"Target colors provided: {len(target_colors)}")
    print(f"Matching blocks found: {len(matched_blocks)}\n")
    print("\n\n".join(matched_blocks))

